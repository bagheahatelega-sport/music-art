export function generateDailyChallenge(clef: 'treble' | 'bass' = 'treble'): SongMetadata {
  const treblePitches = ['C4', 'D4', 'E4', 'F4', 'G4', 'A4', 'B4', 'C5', 'D5'];
  const bassPitches = ['C3', 'D3', 'E3', 'F3', 'G3', 'A3', 'B3', 'C4'];
  const pool = clef === 'treble' ? treblePitches : bassPitches;

  const notes: NoteInfo[] = [];
  let beat = 0;
  for (let i = 0; i < 12; i++) {
    const randomPitch = pool[Math.floor(Math.random() * pool.length)];
    const duration = [1, 2][Math.floor(Math.random() * 2)] as 1 | 2;
    notes.push(createNote(`daily_${i}`, randomPitch, duration, beat, clef, `#${i + 1}`));
    beat += duration;
  }

  const todayStr = new Date().toLocaleDateString('id-ID', {
    day: 'numeric',
    month: 'long',
    year: 'numeric',
  });

  return {
    id: `daily_${Date.now()}`,
    title: `Tantangan Harian (${todayStr})`,
    composer: 'Daily AI Seed',
    category: 'Latihan',
    difficulty: 'Menengah',
    clef,
    bpm: 84,
    timeSignature: [4, 4],
    keySignature: 'C Mayor',
    description: '12 not acak untuk menguji kecepatan membaca not balok dan konsistensi timing harian Anda.',
    notes,
  };
}

