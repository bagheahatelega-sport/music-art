import { pitchToMidi } from '../audio/soundEngine';

function createNote(
  id: string,
  pitch: string,
  duration: NoteDuration,
  beatOffset: number,
  clef: 'treble' | 'bass' = 'treble',
  lyric?: string,
  solfege?: string
): NoteInfo {
  const step = pitch[0];
  const octave = parseInt(pitch[pitch.length - 1], 10);
  const accidental = pitch.includes('#') ? '#' : pitch.includes('b') ? 'b' : null;
  const midi = pitchToMidi(pitch);

  return {
    id,
    pitch,
    step,
    octave,
    accidental,
    midi,
    duration,
    beatOffset,
    clef,
    lyric,
    solfege,
  };
}

